// writeClaudeFixture drops the fixture where the cloner looks for it and
// returns the source path. HOME is redirected so nothing touches the real
// ~/.claude.
func writeClaudeFixture(t *testing.T, slug string) string {
	t.Helper()
	home := t.TempDir()
	t.Setenv("HOME", home)
	dir := filepath.Join(home, ".claude", "projects", slug)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	src := filepath.Join(dir, "src-1.jsonl")
	if err := os.WriteFile(src, []byte(claudeCloneFixture), 0o644); err != nil {
		t.Fatal(err)
	}
	return src
}

// cloneLines decodes a clone back into one descriptor per line so the
// assertions read like the transcript: "user:first", "assistant:answer
// one", "system:compact_boundary:gap compaction", "attachment". Every
// line must carry the new session id.
func cloneLines(t *testing.T, path, wantSessionID string) []string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, raw := range strings.Split(strings.TrimSpace(string(data)), "\n") {
		var m map[string]any
		if err := json.Unmarshal([]byte(raw), &m); err != nil {
			t.Fatalf("clone line is not JSON: %v: %s", err, raw)
		}
		if m["sessionId"] != wantSessionID {
			t.Fatalf("line kept sessionId %v, want %s: %s", m["sessionId"], wantSessionID, raw)
		}
		typ, _ := m["type"].(string)
		switch typ {
		case "system":
			sub, _ := m["subtype"].(string)
			content, _ := m["content"].(string)
			out = append(out, "system:"+sub+":"+content)
		case "user", "assistant":
			out = append(out, typ+":"+claudeTestLineText(m))
		default:
			out = append(out, typ)
		}
	}
	return out
}

func claudeTestLineText(m map[string]any) string {
	msg, _ := m["message"].(map[string]any)
	switch c := msg["content"].(type) {
	case string:
		return c
	case []any:
		var parts []string
		for _, b := range c {
			item, _ := b.(map[string]any)
			switch item["type"] {
			case "text":
				text, _ := item["text"].(string)
				parts = append(parts, text)
			case "tool_use", "tool_result":
				parts = append(parts, item["type"].(string))
			}
		}
		return strings.Join(parts, "+")
	}
	return ""
}

func hasLine(lines []string, substr string) bool {
	for _, l := range lines {
		if strings.Contains(l, substr) {
			return true
		}
	}
	return false
}

// TestClaudeCloneSessionCutsAtServerTurns pins the contract the server
// relies on: turnIndex N counts Command rows, so the clone must end with
// the N-th PROMPT's turn — not the N-th user-typed line. Before this the
// compaction summary, the meta caveat and the slash-command echoes each
// counted as a turn, so a fork of any compacted session landed one or
// more turns early (the anchor turn itself was the first casualty).
func TestClaudeCloneSessionCutsAtServerTurns(t *testing.T) {
	const wd = "/tmp/fixture"
	cases := []struct {
		name      string
		turnIndex int
		wantLast  string // substring of the clone's final line
		wantHave  []string
		wantMiss  []string
	}{
		{
			name: "turn 1", turnIndex: 1,
			wantLast: "last-prompt",
			wantHave: []string{"user:first", "assistant:answer one"},
			wantMiss: []string{"user:second"},
		},
		{
			// The compaction inside turn 2's tool loop is part of turn 2 and
			// stays; the one turn 3's process wrote just before its prompt
			// is trimmed along with its summary.
			name: "turn 2 keeps its mid-turn compaction, drops the next turn's", turnIndex: 2,
			wantLast: "ai-title",
			wantHave: []string{
				"assistant:answer two",
				"system:compact_boundary:mid-turn compaction",
				"user:mid-turn summary",
			},
			wantMiss: []string{
				"system:compact_boundary:gap compaction",
				"user:gap summary",
				"user:third",
			},
		},
		{
			// The auto-compaction that preceded turn 3 is history turn 3 was
			// answered against, so it stays. The manual /compact after it is
			// Command 4 and goes — every one of its four user lines.
			name: "turn 3 ends before the manual /compact", turnIndex: 3,
			wantLast: "mode",
			wantHave: []string{
				"system:compact_boundary:gap compaction",
				"user:gap summary",
				"user:third",
				"assistant:answer three",
			},
			wantMiss: []string{
				"system:compact_boundary:manual compaction",
				"user:manual summary",
				"<local-command-caveat>",
				"<command-name>",
				"<local-command-stdout>",
				"user:fourth",
			},
		},
		{
			name: "turn 4 is the /compact command itself", turnIndex: 4,
			wantLast: "<command-name>",
			wantHave: []string{
				"system:compact_boundary:manual compaction",
				"user:manual summary",
			},
			wantMiss: []string{"user:fourth"},
		},
		{
			name: "turn 5 after a manual compaction", turnIndex: 5,
			wantLast: "assistant:answer four",
			wantHave: []string{"user:fourth"},
			wantMiss: []string{"user:fifth"},
		},
		{
			name: "last turn keeps the whole file", turnIndex: 6,
			wantLast: "last-prompt",
			wantHave: []string{"assistant:answer five"},
		},
		{
			name: "past the end keeps the whole file", turnIndex: 99,
			wantLast: "last-prompt",
			wantHave: []string{"assistant:answer five"},
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			src := writeClaudeFixture(t, claudeProjectSlug(wd))
			a := &ClaudeCodeAdapter{}
			newID, err := a.CloneSession(context.Background(), wd, "src-1", tc.turnIndex)
			if err != nil {
				t.Fatalf("CloneSession: %v", err)
			}
			dst := filepath.Join(filepath.Dir(src), newID+".jsonl")
			lines := cloneLines(t, dst, newID)
			if len(lines) == 0 {
				t.Fatal("clone is empty")
			}
			if last := lines[len(lines)-1]; !strings.Contains(last, tc.wantLast) {
				t.Errorf("clone ends with %q, want it to end with %q\n%s", last, tc.wantLast, strings.Join(lines, "\n"))
			}
			for _, want := range tc.wantHave {
				if !hasLine(lines, want) {
					t.Errorf("clone is missing %q\n%s", want, strings.Join(lines, "\n"))
				}
			}
			for _, miss := range tc.wantMiss {
				if hasLine(lines, miss) {
					t.Errorf("clone should not contain %q\n%s", miss, strings.Join(lines, "\n"))
				}
			}
		})
	}
}

// A whole-file clone must reproduce every source line: the copy loop
// re-decodes with UseNumber and encodes without HTML escaping precisely so
// the round trip changes nothing but sessionId.
func TestClaudeCloneSessionRoundTripsEveryLine(t *testing.T) {
	const wd = "/tmp/fixture"
	src := writeClaudeFixture(t, claudeProjectSlug(wd))
	a := &ClaudeCodeAdapter{}
	newID, err := a.CloneSession(context.Background(), wd, "src-1", 99)
	if err != nil {
		t.Fatalf("CloneSession: %v", err)
	}
	got, err := os.ReadFile(filepath.Join(filepath.Dir(src), newID+".jsonl"))
	if err != nil {
		t.Fatal(err)
	}
	srcLines := strings.Split(strings.TrimSpace(claudeCloneFixture), "\n")
	gotLines := strings.Split(strings.TrimSpace(string(got)), "\n")
	if len(gotLines) != len(srcLines) {
		t.Fatalf("clone has %d lines, source has %d", len(gotLines), len(srcLines))
	}
	for i := range srcLines {
		var want, have map[string]any
		if err := json.Unmarshal([]byte(srcLines[i]), &want); err != nil {
			t.Fatal(err)
		}
		if err := json.Unmarshal([]byte(gotLines[i]), &have); err != nil {
			t.Fatal(err)
		}
		want["sessionId"] = newID
		w, _ := json.Marshal(want)
		h, _ := json.Marshal(have)
		if string(w) != string(h) {
			t.Errorf("line %d changed in the clone:\n  src: %s\n  got: %s", i+1, srcLines[i], gotLines[i])
		}
	}
	// The JSON escape for `<` is a backslash followed by "u003c"; it is
	// assembled at runtime so the source never contains the escape itself.
	escapedLT := string(rune(92)) + "u003c"
	if strings.Contains(string(got), escapedLT) {
		t.Error("clone HTML-escaped `<`; the CLI writes it literally")
	}
	if !strings.Contains(string(got), `"preTokens":180000`) {
		t.Error("clone reformatted an integer; numbers must round-trip byte-identical")
	}
}

