// Claude Code's rule is `replace(/[^a-zA-Z0-9]/g, "-")`. Replacing only
// `/` made every workdir with a dot or underscore in it a clone-source miss.
func TestClaudeProjectSlug(t *testing.T) {
	for in, want := range map[string]string{
		"/home/kyle/foo":       "-home-kyle-foo",
		"/tmp/my.app_v2 x":     "-tmp-my-app-v2-x",
		"/Users/k/Sites/a-b.c": "-Users-k-Sites-a-b-c",
	} {
		if got := claudeProjectSlug(in); got != want {
			t.Errorf("claudeProjectSlug(%q) = %q, want %q", in, got, want)
		}
	}
}

